"""Shared experiment data-assembly path (Sec. 3.1 point-in-time panel construction).

Every experiment script calls `build_experiment_panel` so there is exactly one
place that decides how the modeling panel is assembled and one place that
records data provenance. The market-state series (which calendar months are
"Down" vs "Up", Eq. 4) is loaded from real S&P 500 index prices through the
QuantX Dataloader; the firm-level ESG scores, accounting controls and
market-based exposures cannot be obtained from the permitted data sources (see
`data/data_loader.py` module docstring and `results/RESULTS.md`,
"Not reproduced") and are generated by `data/generate_synthetic.py` with the
paper's reported sample dimensions and ESG descriptive statistics.
"""
from __future__ import annotations

import logging
from pathlib import Path

import pandas as pd

from data.data_loader import DataloaderError, MassiveError, load_ohlcv
from data.generate_synthetic import generate_market_months, generate_panel
from src import config
from src.real_data_pipeline import build_real_firm_month_panel

logger = logging.getLogger(__name__)


def load_real_market_months(use_cache: bool = True) -> tuple[pd.DataFrame, dict]:
    """Real monthly S&P 500 (SPY-proxy) returns over the sample period (Eq. 4 Down/Up input).

    Returns a ``month_id``/``market_return`` frame built from daily SPY bars
    loaded through the QuantX Dataloader, plus the loader's metadata dict
    (``ticker_details``, ``failed``, ``non_massive_source``) for logging.
    """
    bars, meta = load_ohlcv(
        [config.MARKET_INDEX_TICKER], config.SAMPLE_START, config.SAMPLE_END,
        timeframe="1d", use_cache=use_cache,
    )
    bars = bars.set_index("date")["close"].sort_index()
    month_end_close = bars.resample("ME").last()
    market_return = month_end_close.pct_change().dropna()
    frame = pd.DataFrame({
        "month_id": market_return.index.to_period("M").to_timestamp(),
        "market_return": market_return.to_numpy(),
    }).reset_index(drop=True)
    return frame, meta


def build_experiment_panel(
    n_firms: int = config.SYNTHETIC_N_FIRMS_RUN,
    esg_down_effect: dict[str, float] | None = None,
    use_real_market_state: bool = True,
) -> tuple[pd.DataFrame, dict]:
    """Assemble the raw firm-month panel used by every experiment script.

    Returns ``(raw_panel, provenance)``. ``provenance`` records whether the
    market state came from real SPY prices (preferred) or a simulated
    fallback, how many months and firms were realized, and that firm-level
    ESG/accounting/exposure variables are synthetic because MSCI ESG data has
    no permitted REST source (see `results/RESULTS.md`).
    """
    provenance: dict = {"universe_size_run": n_firms}
    market_months = None
    if use_real_market_state:
        try:
            market_months, loader_meta = load_real_market_months()
            provenance["market_state_source"] = "real SPY monthly returns via QuantX Dataloader"
            provenance["market_state_ticker_details"] = loader_meta.get("ticker_details")
            provenance["market_state_non_massive_source"] = loader_meta.get("non_massive_source")
            provenance["n_months_realized"] = int(len(market_months))
            provenance["n_down_months_realized"] = int((market_months["market_return"] < 0).sum())
            provenance["n_up_months_realized"] = int((market_months["market_return"] >= 0).sum())
        except DataloaderError as exc:
            logger.warning("Real SPY market data unavailable (%s); using a simulated market-state fallback.", exc)
            provenance["market_state_source"] = f"simulated fallback (Dataloader error: {exc})"
    else:
        provenance["market_state_source"] = "simulated (use_real_market_state=False)"

    # esg_down_effect injects a known coefficient to check sign/magnitude recovery
    # (tests only); it has no counterpart in real MSCI data, so such calls always
    # use the synthetic panel. Real experiment runs (esg_down_effect=None) try the
    # real market/accounting pipeline first (Sec. 3.1-3.2) and fall back to the
    # synthetic panel only if that data genuinely cannot be loaded.
    if esg_down_effect is None and market_months is not None:
        try:
            raw_panel, real_provenance = build_real_firm_month_panel(n_firms, market_months)
            provenance.update(real_provenance)
            provenance["esg_source"] = "synthetic (MSCI IAS/WAKIS/E/S/G have no permitted REST API; see results/RESULTS.md)"
            provenance["accounting_source"] = "real Massive annual fundamentals, 6-month reporting lag (see results/RESULTS.md)"
            provenance["market_outcomes_source"] = "real OHLCV via QuantX Dataloader (Loss, log RVOL, log CHL, Beta24, RVOL12, CHL12, momentum, Amihud)"
            provenance["n_firm_months"] = int(len(raw_panel))
            logger.info("Experiment panel provenance: %s", provenance)
            return raw_panel, provenance
        except (DataloaderError, MassiveError) as exc:
            logger.warning("Real firm-level panel unavailable (%s); using the synthetic panel.", exc)
            provenance["real_panel_error"] = str(exc)

    provenance.setdefault(
        "esg_source", "synthetic (MSCI IAS/WAKIS/E/S/G have no permitted REST API; see results/RESULTS.md)",
    )
    provenance.setdefault(
        "accounting_source", "synthetic (Compustat items are a licensed WRDS product; see results/RESULTS.md)",
    )
    raw_panel = generate_panel(
        n_firms=n_firms,
        n_months=config.N_MONTHS_PAPER,
        seed=config.SYNTHETIC_SEED,
        esg_down_effect=esg_down_effect,
        market_months=market_months,
    )
    provenance.setdefault("n_months_realized", raw_panel["month_id"].nunique())
    provenance["n_firm_months"] = int(len(raw_panel))
    logger.info("Experiment panel provenance: %s", provenance)
    return raw_panel, provenance
